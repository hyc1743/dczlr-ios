"""Emit the self-authored XX checker used by the iOS diagnostic."""
import argparse
from pathlib import Path
from xx_cases import diagnostic_fixture


def source():
    data = diagnostic_fixture()
    rows = ["    " + ",".join(f"0x{b:02x}" for b in data[i:i + 16]) + "," for i in range(0, len(data), 16)]
    return "/* Generated by tools/generate_xx_fixture.py; entirely self-authored. */\n" + \
        "static const uint8_t dc_diagnostic_xx[] = {\n" + "\n".join(rows) + "\n};\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[1] / "ios/Native/dc_diagnostic_xx.h"
    if args.check:
        if path.read_text() != source(): raise SystemExit("XX diagnostic fixture is stale")
    else:
        path.write_text(source(), encoding="utf-8", newline="\n")
